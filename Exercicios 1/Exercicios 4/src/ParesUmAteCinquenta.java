public class ParesUmAteCinquenta {
    public static void main(String[] args) {

        //Programa que utiliza laço for e estrutura condicional If.k
        //Programa que imprime os números pares de 1 até 50.

        for (int contador = 1; contador <= 50; contador++) {
            if (contador % 2 == 0) {
                System.out.println(contador);

            }
        }
    }
}
