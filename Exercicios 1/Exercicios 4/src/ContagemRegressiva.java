public class ContagemRegressiva {
    public static void main(String[] args) {

        //Programa que utiliza o Estrutura Condicional While.
        //Programa que imprime um os números enquanto a condição for verdadeira. A condição de imprimir os números de 10 até 0, menores ou igual a 0.

        int contador = 10;
        while (contador >= 0) {
            System.out.println(contador);
            contador--;
        }

    }
}
